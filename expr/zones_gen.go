//go:build ignore

package main

import (
	"archive/zip"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "zones_gen: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	goroot := runtime.GOROOT()
	if goroot == "" {
		return fmt.Errorf("runtime.GOROOT() is empty")
	}
	zipPath := filepath.Join(goroot, "lib", "time", "zoneinfo.zip")
	r, err := zip.OpenReader(zipPath)
	if err != nil {
		return fmt.Errorf("open %s: %w", zipPath, err)
	}
	defer r.Close()

	names := make([]string, 0, len(r.File))
	for _, f := range r.File {
		if strings.HasSuffix(f.Name, "/") || f.FileInfo().IsDir() {
			continue
		}
		names = append(names, f.Name)
	}
	sort.Strings(names)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by zones_gen.go; DO NOT EDIT.\n")
	buf.WriteString("package expr\n\n")
	buf.WriteString("var zoneNames = []string{\n")
	for _, name := range names {
		fmt.Fprintf(&buf, "\t%q,\n", name)
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format generated source: %w", err)
	}

	outPath := filepath.Join("expr", "zones_data.go")
	if _, err := os.Stat("zones_gen.go"); err == nil {
		outPath = "zones_data.go"
	}
	if err := os.WriteFile(outPath, formatted, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", outPath, err)
	}
	return nil
}
